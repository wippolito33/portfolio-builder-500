const SECTOR_OF = {};
for (const [sector, list] of Object.entries(SECTOR_LIST)) {
  for (const t of list.split(/\s+/)) if (t) SECTOR_OF[t] = sector;
}

function sectorFor(holding) {
  if (holding.isCash) return "Cash";
  const s = holding.symbol.toUpperCase();
  return SECTOR_OF[s] || SECTOR_OF[s.replace(".", "-")] || SECTOR_OF[s.replace("-", ".")] || "Other";
}
